// data/sprites.js — moldes dos personagens da V2 (26×48, estilo chibi), paletas e fontes.
// Legenda dos moldes (ver js/game/chars.js): "." vazio, "o" contorno de dentro (o de fora é
// calculado), "_" apaga, "*" brilho do olho; cada letra é um material pintado pela paleta da roupa
// (Apêndice A), que vira uma rampa de tons com luz de cima e da esquerda.
// Cabeça: linhas 0 a 20 do sprite. Tronco: a partir da linha 19. Pernas: a partir da linha 33. Os
// pés ficam na linha 46 (a 47 é o contorno).

// Ajudas para escrever os moldes de 26 colunas (cada molde vira uma lista de linhas de 26):
//   padRows(linhas)   completa cada linha com "." até 26 colunas
//   symRows(linhas)   linhas de até 13 colunas são a metade esquerda, espelhada para a direita
//                     (moldes de frente e de costas); linhas de 26 ficam como estão
//   mirrorRows(linhas)        espelha o molde inteiro (o outro passo do andar)
//   liftLeg(linhas, lado, de, dy)   sobe dy linhas a perna de um lado ('left' ou 'right'), da
//                     linha `de` para baixo (o pé que sai do chão no passo, de frente e de costas)
//   swapLetters(linhas, { a: 'b' })   troca letras
function padRows(rows) { return rows.map(r => r.padEnd(26, '.')); }
function symRows(rows) {
  return rows.map(r => (r.length > 13 ? r.padEnd(26, '.') : r.padEnd(13, '.') + [...r.padEnd(13, '.')].reverse().join('')));
}
function mirrorRows(rows) { return rows.map(r => [...r].reverse().join('')); }
function liftLeg(rows, side, from, dy) {
  const [x0, x1] = side === 'left' ? [0, 13] : [13, 26];
  return rows.map((r, y) => {
    if (y < from) return r;
    const src = rows[y + dy] || '.'.repeat(26);
    return r.slice(0, x0) + src.slice(x0, x1) + r.slice(x1);
  });
}
function swapLetters(rows, map) { return rows.map(r => r.replace(/./g, c => (map[c] !== undefined ? map[c] : c))); }

